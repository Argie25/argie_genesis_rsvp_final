create table if not exists public.rsvps (
 id bigint generated by default as identity primary key,
 full_name text not null check (length(trim(full_name)) between 1 and 120),
 email text check (length(email) <= 254),
 attending boolean not null,
 guests integer not null,
 attendee_names text[] not null default '{}',
 message text check (length(message) <= 2000),
 created_at timestamptz not null default now(),
 constraint rsvps_guests_check check (guests between 0 and 10),
 constraint rsvps_attendance_check check (
   (attending and guests between 1 and 10 and cardinality(attendee_names) = guests)
   or (not attending and guests = 0 and cardinality(attendee_names) = 0)
 )
);
alter table public.rsvps enable row level security;
drop policy if exists "Anyone can submit wedding RSVP" on public.rsvps;
create policy "Anyone can submit wedding RSVP" on public.rsvps for insert to anon, authenticated with check (true);
revoke all on public.rsvps from anon, authenticated;
grant insert on public.rsvps to anon, authenticated;
grant usage on sequence public.rsvps_id_seq to anon, authenticated;
-- No public read, update, or delete policy.
